-- FORMAS DE CORREÇÃO - 1FN
-- PRIMEIRA CORREÇÃO DA TABELA SERIA ELIMINAR GRUPOS REPETITIVOS COMO PRODUTOS, PRODUTO2, PRODUTO3
-- A FORMA 1FN FAZ SENTIDO AQUI POR QUE UM PEDIDO PODE POSSUIR QUALQUER QUANTIDADE DE ITENS SEM CRIAR NOVAS COLUNAS

-- FORMA DE CORREÇÃO - 2FN
-- SEPARAR CLIENTE, PRODUTO E CATEGORIA
-- OS DADOS DE CLIENTE NÃO PERTENCEM AO PEDIDO, ELES DESCREVEM O CLIENTE. O NOME CATEGORIA TAMBEM NÃO DEVE SER REPETIDO
-- CHAVE É COMPOSTA POR (ID_PEDIDO E _ID_CLIENTE)
-- PEDIDO DEPENDE DE CLIENTE
-- A 2FN APARECE DE FORMA CONCRETA: EM UMA CHAVE COMPOSTA, ATRIBUTOS COMUNS DEPENDER DA CHAVE INTEIRA

-- FORMA DE CORREÇÃO - 3FN
-- VERSÃO INCORRETA DE PRODUTO
-- NOME_CATEGORIA DEPENDE DE ID_CATEGORIA. PORTANTO, ELE DEVE ESTAR EM CATEGORIA

-- RESUMO
-- 1FN RESOLVE GRUPOS REPETITIVOS
-- 2FN RESOLVE DEPENDENCIAS PARCIAIS
-- 3FN REMOVE DEPENDENCIAS INDEVIDAS ENTRE ATRIBUTOS NÃO CHAVE

-- REDUNDÂNCIA QUE DEVE PERMANECER
-- ITEM_PEDIDO.PRECO_UNITARIO DEVE GUARDAR O PREÇO PRATICO NO MOMENTO DA VENDA.

-- MESMO QUE PRODUTO, PREÇO MUDE AMANHÃ, O HISTÓRICO DO PEDIDO PRECISA CONTINUAR CORRETO


